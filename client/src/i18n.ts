type Path<T, Prefix extends string = ""> = T extends object
  ? {
      [K in keyof T & string]: T[K] extends (...args: any[]) => any
        ? `${Prefix}${K}`
        : T[K] extends object
          ? Path<T[K], `${Prefix}${K}.`>
          : `${Prefix}${K}`;
    }[keyof T & string]
  : never;

export type StringKey = Path<typeof strings>;

/** Simple dotted-path lookup — "decision.approve" -> "اعتماد". A missing key renders
 *  loudly ("?key?") instead of throwing, so a typo surfaces on screen during review. */
export function t(key: StringKey): any {
  const parts = key.split(".");
  let node: any = strings;
  for (const part of parts) {
    node = node?.[part];
  }
  if (node === undefined) return `?${key}?`;
  return node;
}

export { strings };
